def language_label(name, metrics, max_width):
    label = LANGUAGE_LABELS.get(name, name)

    def text_width(text):
        return sum(metrics.get(character, 0.7) for character in text) * 24

    if text_width(label) <= max_width:
        return label
    while label and text_width(label.rstrip() + "…") > max_width:
        label = label[:-1]
    return label.rstrip() + "…"


def saturate(color):
    rgb = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    hue, lightness, saturation = colorsys.rgb_to_hls(*rgb)
    rgb = colorsys.hls_to_rgb(hue, lightness, min(1, saturation * 1.35))
    return "#" + "".join(f"{round(channel * 255):02x}" for channel in rgb)


def shift_hue(color, degrees, saturation_scale=1, lightness_scale=1):
    rgb = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    hue, saturation, value = colorsys.rgb_to_hsv(*rgb)
    rgb = colorsys.hsv_to_rgb((hue + degrees / 360) % 1, min(1, saturation * saturation_scale), value)
    hue, lightness, saturation = colorsys.rgb_to_hls(*rgb)
    rgb = colorsys.hls_to_rgb(hue, min(1, lightness * lightness_scale), saturation)
    return "#" + "".join(f"{round(channel * 255):02x}" for channel in rgb)


def render_card(rows, total):
    font_path = Path(__file__).resolve().parent.parent / "assets/fonts/Pliant-digits.woff"
    font_data = base64.b64encode(font_path.read_bytes()).decode("ascii")
    title_font_data = base64.b64encode(font_path.with_name("Manrope-Medium.ttf").read_bytes()).decode("ascii")
    font_metrics = json.loads(font_path.with_name("Pliant-digits-metrics.json").read_text())
    title_metrics = json.loads(font_path.with_name("title-metrics.json").read_text())
    # Keep reading order on four columns: wide, square, square, square, repeat.
    cell = 171
    gap = 12
    tile_height = cell
    row_step = tile_height + gap
    placements = []
    row = column = 0
    for index, (name, count) in enumerate(rows):
        span = 2 if index % 4 == 0 else 1
        if column + span > 4:
            row += 1
            column = 0
        placements.append((name, count, row, column, span))
        column += span
    height = 128 + (row + 1) * row_step - gap
    svg = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="800" height="{height}" viewBox="0 0 800 {height}" role="img" aria-labelledby="title desc">',
        f'<style>@font-face{{font-family:Manrope;src:url(data:font/ttf;base64,{title_font_data}) format("truetype");font-weight:500;font-style:normal;}}'
        f'@font-face{{font-family:Pliant;src:url(data:font/woff;base64,{font_data}) format("woff");font-weight:200 600;font-stretch:100% 125%;}}</style>',
        '<title id="title">Languages %</title>',
        '<desc id="desc">Language shares by code size, excluding forks. Build files, containers and shell scripts are grouped into Other.</desc>',
        '<defs><filter id="acrylic-noise" x="0" y="0" width="100%" height="100%" color-interpolation-filters="sRGB"><feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="3" seed="7" stitchTiles="stitch"/><feColorMatrix type="saturate" values="0"/><feComposite in2="SourceGraphic" operator="in"/></filter></defs>',
        f'<path d="{contour(0, 0, 800, height, 40)}" fill="#222222"/>',
        f'<path d="{contour(.75, .75, 798.5, height - 1.5, 39.25)}" fill="none" stroke="#999999" stroke-opacity="0.266667" stroke-width="1.5"/>',
        '<g font-family="Manrope, sans-serif" fill="#ffffff">',
        '<text x="40" y="58" font-size="24" font-weight="500">Languages %</text>',
    ]
    for index, (name, count, row, column, span) in enumerate(placements):
        x = 40 + column * (cell + gap)
        y = 88 + row * row_step
        width = cell * span + gap * (span - 1)
        color = COLORS.get(name, "#999999")
        bright = "#" + "".join(f"{round(int(color[i:i + 2], 16) * 0.8 + 255 * 0.2):02x}" for i in (1, 3, 5))
        color, bright = saturate(color), saturate(bright)
        counter_color = shift_hue(color, -20, saturation_scale=1.2, lightness_scale=0.9)
        percentage = 100 * count / total
        label = f"{percentage:.0f}" if percentage > 9 else f"{percentage:.1f}"
        number_font = "Pliant"
        display_name = language_label(name, title_metrics, cell - 40)
        title_width = sum(title_metrics.get(c, 0.7) for c in display_name) * 24
        available_width = max(1, width - 40 - title_width - 2)
        target_height = tile_height - 40
        fitted = None
        weight = 600
        for candidate in sorted(map(int, font_metrics["widths"]), reverse=True):
            glyphs = font_metrics["variants"][str(weight)][str(candidate)]
            advance = 0
            left, right = float("inf"), float("-inf")
            bottom, top = float("inf"), float("-inf")
            for character in label:
                glyph = glyphs[character]
                x_min, y_min, x_max, y_max = glyph["bounds"]
                left = min(left, advance + x_min)
                right = max(right, advance + x_max)
                bottom = min(bottom, y_min)
                top = max(top, y_max)
                advance += glyph["advance"]
            if span == 2:
                scale = min(target_height / (top - bottom), tile_height * 0.9 / font_metrics["unitsPerEm"])
                fits = (right - left) * scale <= available_width
            else:
                # Fill the available width, with font-size capped at 60% of the tile height.
                scale = min((width - 40) / (right - left), tile_height * 0.6 / font_metrics["unitsPerEm"])
                fits = True
            fitted = (weight, candidate, left, right, bottom, top, scale)
            if fits:
                break
        if not fitted:
            raise RuntimeError("Pliant cannot fit the number at its maximum tile height")
        number_weight, number_width, left, right, bottom, top, scale = fitted
        units = font_metrics["unitsPerEm"]
        number_size = scale * units
        number_x = x + width - 20 - right * scale
        number_y = y + tile_height - 20 + bottom * scale
        width_style = f"font-variation-settings: 'wdth' {number_width}, 'wght' {number_weight};font-stretch:{number_width}%"
        svg.extend([
            f'<defs><radialGradient id="language-{index}" gradientUnits="userSpaceOnUse" cx="{x + width * 1.5}" cy="{y - tile_height * 0.5}" r="760"><stop offset="0" stop-color="{bright}" stop-opacity="0.75"/><stop offset="1" stop-color="{color}" stop-opacity="0.07"/></radialGradient></defs>',
            f'<path d="{contour(x, y, width, tile_height, 32)}" fill="url(#language-{index})"/>',
            f'<defs><radialGradient id="language-counter-{index}" gradientUnits="userSpaceOnUse" cx="{x - 50}" cy="{y + tile_height + 30}" r="300"><stop offset="0" stop-color="{counter_color}" stop-opacity="0.5"/><stop offset="1" stop-color="{counter_color}" stop-opacity="0"/></radialGradient></defs>',
            f'<path d="{contour(x, y, width, tile_height, 32)}" fill="url(#language-counter-{index})"/>',
            f'<text x="{number_x:.3f}" y="{number_y:.3f}" font-family="{number_font}, sans-serif" style="{width_style}" font-size="{number_size:.3f}" font-weight="{number_weight}" fill="#ffffff" fill-opacity="0.6">{label}</text>',
            f'<path d="{contour(x, y, width, tile_height, 32)}" fill="#ffffff" filter="url(#acrylic-noise)" opacity="0.12"/>',
            f'<path d="{contour(x + .75, y + .75, width - 1.5, tile_height - 1.5, 31.25)}" fill="none" stroke="#999999" stroke-opacity="0.266667" stroke-width="1.5"/>',
            f'<text x="{x + 20}" y="{y + 44}" font-size="24" font-weight="500" fill="#ffffff" fill-opacity="0.72">{escape(display_name)}</text>',
        ])
    svg.extend(['</g>', '</svg>'])
    return "\n".join(svg) + "\n"


